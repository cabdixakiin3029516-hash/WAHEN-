class Product {
  final String id;
  final String name;
  final String category;
  final double price;
  final String imageEmoji;
  final double rating;
  final String seller;
  final String description;

  const Product({
    required this.id,
    required this.name,
    required this.category,
    required this.price,
    required this.imageEmoji,
    required this.rating,
    required this.seller,
    required this.description,
  });
}
